#!/usr/bin/env node
// Generate DSH >=0.2 bundle patches for the router presets.
//
// DSH 0.2's agent-preset-registry no longer scans ~/.dsh/.agent-presets/;
// a preset is a loader row `@deepseek-ai/dsh-agent-preset` inserted by a bundle
// patch. This script wraps each `<preset>/agent.cordis.yml` (kept as the single
// source of truth) into such a row, writing `bundle/<preset>.patch.yml`.
//
// - Relative module names (`./x.mjs`) resolve against the PROFILE tree's
//   baseUrl, not this package, so they are rewritten to absolute file URLs.
// - `@deepseek-ai/dsh-workflow-worker-thread` was removed in DSH 0.2; it is
//   replaced by `@deepseek-ai/dsh-workflow-ptc` as in the official standard preset.
//
// Usage: node scripts/gen-bundle-patch.mjs   (re-run after editing a preset)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createRequire } from 'node:module'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PRESETS = ['router-standard', 'router-spec', 'router-react']
const OUT = join(ROOT, 'bundle')

// Best-effort validation with the loader's YAML dialect (js-yaml + !!js).
function loadYaml() {
  const candidates = [process.env.DSH_CHECKOUT, '/home/ubuntu/.local/lib/node_modules/@deepseek-ai/dsh']
  for (const dir of candidates.filter(Boolean)) {
    try { return createRequire(join(dir, 'package.json'))('js-yaml') } catch {}
  }
  return null
}

function meta(dir) {
  const out = {}
  for (const line of readFileSync(join(dir, 'preset.yml'), 'utf8').split('\n')) {
    const m = /^(name|description|order):\s*(.*)$/.exec(line)
    if (m) out[m[1]] = m[2].trim()
  }
  return out
}

mkdirSync(OUT, { recursive: true })
const yaml = loadYaml()

for (const id of PRESETS) {
  const dir = join(ROOT, id)
  let body = readFileSync(join(dir, 'agent.cordis.yml'), 'utf8')

  body = body.replace(/^(\s*name:\s*)'?(\.\/[^'\s]+)'?\s*$/gm, (_, head, rel) =>
    `${head}'${new URL(rel, pathToFileURL(dir + '/')).href}'`)
  body = body.replace(
    /- id: workflow-worker-thread\n(\s*)name: '@deepseek-ai\/dsh-workflow-worker-thread'/,
    "- id: workflow-ptc\n$1name: '@deepseek-ai/dsh-workflow-ptc'")
  if (/dsh-workflow-worker-thread|name:\s*'?\.\//.test(body)) throw new Error(`${id}: unconverted row left`)

  const m = meta(dir)
  const indented = body.split('\n').map((l) => (l.length ? '          ' + l : l)).join('\n')
  const header = [
    `# GENERATED by scripts/gen-bundle-patch.mjs from ${id}/agent.cordis.yml — do not edit.`,
    '- insert:',
    `    - id: preset-${id}`,
    "      name: '@deepseek-ai/dsh-agent-preset'",
    '      config:',
    `        id: ${id}`,
    `        name: ${m.name}`,
    `        description: ${m.description}`,
    ...(m.order ? [`        order: ${m.order}`] : []),
    '        plugins:',
  ].join('\n')
  const text = `${header}\n${indented.replace(/\s*$/, '')}\n`

  if (yaml) {
    const JsExpr = new yaml.Type('tag:yaml.org,2002:js', { kind: 'scalar', construct: (s) => ({ __js: s }) })
    const doc = yaml.load(text, { schema: yaml.DEFAULT_SCHEMA.extend([JsExpr]) })
    const row = doc[0].insert[0]
    if (row.config.id !== id || !Array.isArray(row.config.plugins) || row.config.plugins.length < 5) {
      throw new Error(`${id}: generated patch failed structural check`)
    }
    console.log(`✓ ${id}: ${row.config.plugins.length} top-level rows`)
  }
  writeFileSync(join(OUT, `${id}.patch.yml`), text)
}
console.log(`wrote ${OUT}`)
